def _runtime_maps(nodes: list[ResolvedNode]) -> tuple[dict[str, str], dict[str, list[str]], dict[str, dict[str, str]]]:
    handlers: dict[str, str] = {}
    roles: dict[str, list[str]] = {}
    ports: dict[str, dict[str, str]] = {}
    for node in nodes:
        runtime = node.definition.runtime
        handler = str(runtime.get("handler", "")).strip()
        aliases = node.definition.runtime_aliases(node.server_typename)
        if handler:
            for alias in aliases:
                handlers[alias] = handler
        node_roles = list(runtime.get("roles", []))
        for alias in aliases:
            if node_roles:
                roles[alias] = node_roles
            port_defaults = {
                key: str(runtime[key])
                for key in ("default_input_port", "default_output_port")
                if str(runtime.get(key, "")).strip()
            }
            if port_defaults:
                ports[alias] = port_defaults
    return handlers, roles, ports


def render_python(nodes: list[ResolvedNode]) -> str:
    handlers, roles, ports = _runtime_maps(nodes)
    return '''# This file is generated by `python -m tools.node_dev generate`.
# Do not edit it by hand. Edit node_defs/*.json instead.
from __future__ import annotations

NODE_TYPE_TO_HANDLER = {handlers}
NODE_TYPE_ROLES = {roles}
NODE_TYPE_DEFAULT_PORTS = {ports}


def handler_id_for(node_type: str) -> str | None:
    return NODE_TYPE_TO_HANDLER.get(str(node_type))


def has_role(node_type: str, role: str) -> bool:
    return role in NODE_TYPE_ROLES.get(str(node_type), ())


def default_port(node_type: str, direction: str, fallback: str) -> str:
    key = "default_output_port" if direction == "output" else "default_input_port"
    return NODE_TYPE_DEFAULT_PORTS.get(str(node_type), {{}}).get(key, fallback)
'''.format(
        handlers=repr(dict(sorted(handlers.items()))),
        roles=repr(dict(sorted(roles.items()))),
        ports=repr(dict(sorted(ports.items()))),
    )


def render_development_catalog(nodes: list[ResolvedNode]) -> str:
    data = {
        "schema_version": 1,
        "generated_by": "python -m tools.node_dev generate",
        "nodes": [node.development_dict() for node in nodes],
    }
    return json.dumps(data, ensure_ascii=False, indent=2) + "\n"


def generated_outputs(registry: NodeRegistry) -> dict[Path, str]:
    nodes = registry.resolve()
    return {
        registry.root / GODOT_TARGET: render_godot(nodes),
        registry.root / GODOT_SOURCES_TARGET: render_godot_sources(nodes),
        registry.root / PYTHON_TARGET: render_python(nodes),
        registry.root / DEVELOPMENT_TARGET: render_development_catalog(nodes),
    }


def write_outputs(registry: NodeRegistry) -> list[str]:
    messages: list[str] = []
    for path, content in generated_outputs(registry).items():
        changed = not path.is_file() or path.read_text(encoding="utf-8") != content
        if changed:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")
        messages.append(f"{'generated' if changed else 'unchanged'} {path.relative_to(registry.root)}")
    return messages


def stale_outputs(registry: NodeRegistry) -> list[Path]:
    stale: list[Path] = []
    for path, content in generated_outputs(registry).items():
        if not path.is_file() or path.read_text(encoding="utf-8") != content:
            stale.append(path)
    return stale


def validate_runtime_handlers(registry: NodeRegistry, nodes: list[ResolvedNode]) -> list[str]:
    handler_path = registry.root / "local_runtime" / "neuralese_local" / "onnx_node_handlers.py"
    if not handler_path.is_file():
        return [f"runtime handler module is missing: {handler_path}"]
    text = handler_path.read_text(encoding="utf-8", errors="replace")
    registered = set()
    for match in __import__("re").finditer(r"@handles\(([^)]*)\)", text):
        registered.update(__import__("re").findall(r'\"([^\"]+)\"', match.group(1)))
    errors: list[str] = []
    for node in nodes:
        handler = str(node.definition.runtime.get("handler", "")).strip()
        if handler and handler not in registered:
            errors.append(f"{node.id}: runtime handler {handler!r} is not registered with @handles")
    return errors
