"""Renders the canonical device script for a platform and a mapping config.

The templates in ``templates/`` are the real, readable source of each device
program; this module only fills in the parts that depend on which sensors and
motors the child picked. Nothing here decides behaviour -- if you want to change
how a robot behaves, you change the template, and every generated script changes
with it.

Generation is deterministic: the same config always produces byte-identical
output, with no timestamps or paths embedded. That is what lets the tests pin the
generated scripts as snapshots and catch accidental changes to device behaviour.
"""

from __future__ import annotations

import re
from pathlib import Path
from typing import Any, Dict, List, Optional

from .codec import MAX_LINE_BYTES, PROTOCOL_VERSION, SEQ_MOD
from .config import MappingPlan, compile_config, config_hash
from .errors import ERR_EXPORT_FAILED, RobotError

TEMPLATE_DIR = Path(__file__).resolve().parent / "templates"

BANNER = "Generated by Neuralese. Do not edit -- export again to change it."

_PLACEHOLDER_RE = re.compile(r"\{\{([A-Z_]+)\}\}")


def _dedupe(items: List[str]) -> List[str]:
    """Preserve first-seen order.

    Two channels on the same physical device share a setup line (the colour
    sensor's reflection and ambient readings are one ``ColorSensor``), and
    constructing it twice would claim the port twice.
    """
    seen = set()
    out: List[str] = []
    for item in items:
        if item and item not in seen:
            seen.add(item)
            out.append(item)
    return out


def _read_sensors_body(plan: MappingPlan) -> str:
    if not plan.input_channels:
        return ""
    lines = ["\n"]
    for channel in plan.input_channels:
        lines.append("        %s,  # %s\n" % (channel.expr, channel.label))
    lines.append("    ")
    return "".join(lines)


def _apply_actuators_body(plan: MappingPlan) -> str:
    if not plan.output_channels:
        return "    pass"
    lines = []
    for index, channel in enumerate(plan.output_channels):
        statement = channel.expr.format(value="values[%d]" % index)
        lines.append("    %s  # %s" % (statement, channel.label))
    return "\n".join(lines)


def _imports(plan: MappingPlan) -> str:
    collected: List[str] = []
    for channel in list(plan.input_channels) + list(plan.output_channels):
        collected.extend(channel.imports)
    return "\n".join(_dedupe(collected))


def _setup(plan: MappingPlan) -> str:
    collected: List[str] = []
    for channel in list(plan.input_channels) + list(plan.output_channels):
        collected.extend(channel.setup)
    return "\n".join(_dedupe(collected))


def _substitutions(plan: MappingPlan, cfg_hash: str) -> Dict[str, str]:
    transport = plan.config.get("transport") or {}
    rate_hz = max(1, plan.rate_hz)
    return {
        "BANNER": BANNER,
        "PROTOCOL": str(PROTOCOL_VERSION),
        "PLATFORM_ID": plan.platform.id,
        "CFG_HASH": cfg_hash,
        "N_IN": str(plan.input_count),
        "N_OUT": str(plan.output_count),
        "RATE_HZ": str(rate_hz),
        "PERIOD_MS": str(int(round(1000.0 / rate_hz))),
        "WATCHDOG_MS": str(plan.watchdog_ms),
        "SEQ_MOD": str(SEQ_MOD),
        "MAX_LINE": str(MAX_LINE_BYTES),
        "BAUD": str(int(transport.get("baud", 115200))),
        "TCP_PORT": str(int(transport.get("port", 9999) or 9999)),
        "SAFE_VALUES": repr(plan.safe_values()),
        "IMPORTS": _imports(plan),
        "SETUP": _setup(plan),
        "READ_SENSORS": _read_sensors_body(plan),
        "APPLY_ACTUATORS": _apply_actuators_body(plan),
    }


def render_template(template_name: str, values: Dict[str, str]) -> str:
    path = TEMPLATE_DIR / template_name
    if not path.exists():
        raise RobotError("Device script template is missing: %s" % path, code=ERR_EXPORT_FAILED)
    text = path.read_text(encoding="utf-8")

    def replace(match: "re.Match[str]") -> str:
        key = match.group(1)
        if key not in values:
            raise RobotError(
                "Device script template %s uses an unknown placeholder {{%s}}." % (template_name, key),
                code=ERR_EXPORT_FAILED,
            )
        return values[key]

    rendered = _PLACEHOLDER_RE.sub(replace, text)
    # A template that still has a placeholder would be handed to a child as a
    # program that cannot even be parsed, so fail here instead.
    leftover = _PLACEHOLDER_RE.search(rendered)
    if leftover:
        raise RobotError(
            "Device script for %s was not fully generated ({{%s}} left over)."
            % (template_name, leftover.group(1)),
            code=ERR_EXPORT_FAILED,
        )
    return rendered


def generate_script(config: Dict[str, Any], model_meta: Optional[Dict[str, Any]] = None) -> str:
    """Validate a config and render the device program for it."""
    plan = compile_config(config, model_meta)
    return generate_script_for_plan(plan)


def generate_script_for_plan(plan: MappingPlan) -> str:
    cfg_hash = config_hash(plan.config)
    values = _substitutions(plan, cfg_hash)
    rendered = render_template(plan.platform.template, values)

    # The device script and the host must agree on the fingerprint, or the robot
    # will be turned away at the handshake it just passed.
    if cfg_hash not in rendered:
        raise RobotError("Generated device script is missing its config fingerprint.", code=ERR_EXPORT_FAILED)
    return rendered


def script_filename(config: Dict[str, Any]) -> str:
    from .platforms import get_platform

    return get_platform(config.get("platform", "")).script_filename
